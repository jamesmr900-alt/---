import asyncio, json
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--use-gl=swiftshader','--enable-unsafe-swiftshader'])
        pg = await b.new_page(viewport={'width':1400,'height':1000})
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda m: m.type=='error' and errs.append(m.text))
        await pg.goto('http://localhost:8790/tools.html#wiz'); await pg.wait_for_function('window.WIZ && window.VOLTUM', timeout=30000)
        await pg.evaluate("""localStorage.setItem('maytoni_help_v1', JSON.stringify({seen:{}, off:true}))""")
        r = await pg.evaluate("""() => { WIZ.setRooms([{name:'Гостиная',L:6,W:4.5,H:2.75,ceiling:'ГКЛ',color:'черный',trackShape:'П',trackSides:'3, 2, 3',strip:6,stripUse:'карниз'},{name:'Кухня',L:4,W:3,H:2.7,ceiling:'натяжной',color:'белый'}]); return document.querySelectorAll('#wTab tr').length }""")
        print('rows', r)
        await pg.select_option('#wCtl','Zigbee')
        opts = await pg.eval_on_selector('#wSys', 'e=>[...e.options].map(o=>o.value)')
        sysx=[o for o in opts if 'EXILITY X' in o and 'GLASY' not in o]; print(sysx)
        await pg.select_option('#wSys', sysx[0])
        await pg.click('#wGo')
        await pg.wait_for_timeout(1500)
        txt = await pg.inner_text('section[data-p="wiz"]')
        print('TRX' in txt, 'DSZ' in txt, txt.count('Трек ('))
        await pg.click('#wToKp'); await pg.wait_for_timeout(1500)
        kp = await pg.evaluate("MTUI.kp.get().rows.map(r=>r.room+' '+r.a+' '+r.qty)")
        print(len(kp), [k for k in kp if 'TR' in k][:12])
        # plan
        await pg.evaluate("showTab('plan')"); await pg.wait_for_timeout(800)
        pl = await pg.evaluate("MTUI.TS.planner.plans.map(p=>p.name+': '+p.items.filter(i=>i.t!=='furn').map(i=>i.t+':'+(i.kind)).join(','))")
        print(pl)
        # delete one auto track lum in plan Гостиная => project qty change
        n0 = await pg.evaluate("PROJECT.data.rows.filter(r=>r.room==='Гостиная'&&/DSZ/.test(r.a)).map(r=>r.qty)")
        await pg.evaluate("""()=>{const T=MTUI.TS.planner; T.cur=T.plans.findIndex(p=>p.name==='Гостиная'); const p=T.plans[T.cur]; const i=p.items.findIndex(i=>i.kind==='track'); p.items.splice(i,1); PLANNER.refresh();}""")
        await pg.wait_for_timeout(1500)
        n1 = await pg.evaluate("PROJECT.data.rows.filter(r=>r.room==='Гостиная'&&/DSZ/.test(r.a)).map(r=>r.qty)")
        kpn = await pg.evaluate("MTUI.kp.get().rows.filter(r=>r.room==='Гостиная'&&/DSZ/.test(r.a)).map(r=>r.qty)")
        cnt = await pg.evaluate("MTUI.TS.planner.plans.find(p=>p.name==='Гостиная').items.filter(i=>i.kind==='track').length")
        print('track qty', n0, '->', n1, 'kp', kpn, 'plan', cnt)
        await pg.click('#p3d'); await pg.wait_for_timeout(2500)
        await pg.screenshot(path='/tmp/s_plan.png', full_page=False)
        await pg.locator('#p3dBox').screenshot(path='/tmp/s_3d.png')
        # control
        await pg.evaluate("showTab('ctl')"); await pg.click('#ctFromKp'); await pg.wait_for_timeout(500)
        print((await pg.inner_text('#ctTab'))[:600])
        # voltum
        await pg.evaluate("showTab('eui')")
        await pg.set_input_files('#vPdf', '/mnt/user-data/uploads/Дизайн-проект__Александровка.pdf')
        await pg.wait_for_function("document.querySelector('#vPdfMsg').textContent.includes('Стр.')||document.querySelector('#vPdfMsg').textContent.includes('не')", timeout=120000)
        print(await pg.inner_text('#vPdfMsg'))
        print(await pg.evaluate("VOLTUM.rows.map(r=>r.type+' → '+r.id+' '+r.qty)"))
        await pg.fill('#vText','Кухня: Розетка 220V 6; Выключатель 2-кл. 1\nСпальня:\nРозетка USB 2\nПереключатель проходной 1-кл.  2')
        await pg.click('#vParse'); await pg.select_option('#vCol','08'); await pg.select_option('#vBlk','2'); await pg.click('#vGo')
        await pg.wait_for_timeout(500)
        print((await pg.inner_text('#vOut'))[:1500])
        await pg.click('#vToKp'); await pg.wait_for_timeout(800)
        print('kp voltum', await pg.evaluate("MTUI.kp.priced().lines.filter(l=>/^VL/.test(l.a)).slice(0,4).map(l=>l.a+' '+l.n)"))
        await pg.locator('section[data-p="eui"]').screenshot(path='/tmp/s_eui.png')
        print('ERR', errs[:8])
        await b.close()
asyncio.run(main())
